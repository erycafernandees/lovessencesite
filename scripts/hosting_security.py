"""Use the same browser policy in HTML and in the static host configuration."""


def browser_policy(is_admin: bool = False) -> str:
    shared = (
        "default-src 'self'; base-uri 'self'; object-src 'none'; "
        "form-action 'self' https://checkout.stripe.com; "
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
        "font-src 'self' https://fonts.gstatic.com; "
        "img-src 'self' data: blob: https://*.supabase.co https://www.clarity.ms https://c.bing.com; "
        "media-src 'self'; connect-src 'self' https://*.supabase.co https://api.stripe.com "
        "https://www.google-analytics.com https://*.google-analytics.com https://*.analytics.google.com "
        "https://*.clarity.ms https://c.bing.com; frame-src 'self' https://challenges.cloudflare.com; "
    )
    scripts = "script-src 'self' https://cdn.jsdelivr.net" if is_admin else (
        "script-src 'self' https://www.googletagmanager.com https://www.clarity.ms https://challenges.cloudflare.com"
    )
    return shared + scripts + "; script-src-attr 'none'"


def host_headers() -> str:
    # Cloudflare joins headers from overlapping rules. Detach the public CSP
    # before applying the admin policy; two policies would intersect and block
    # the admin's Supabase SDK. srcdoc email previews retain frame-src 'self'.
    result = (
        "# Generated by scripts/hosting_security.py; GitHub Pages ignores this file.\n"
        "/*\n"
        "  X-Content-Type-Options: nosniff\n"
        "  X-Frame-Options: DENY\n"
        "  Referrer-Policy: no-referrer\n"
        "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(self \"https://checkout.stripe.com\")\n"
        "  Strict-Transport-Security: max-age=31536000\n"
        f"  Content-Security-Policy: {browser_policy()}; frame-ancestors 'none'; upgrade-insecure-requests\n"
    )
    for route in ("/admin", "/admin/*"):
        result += (
            f"\n{route}\n"
            "  ! Content-Security-Policy\n"
            f"  Content-Security-Policy: {browser_policy(True)}; frame-ancestors 'none'; upgrade-insecure-requests\n"
            "  Cache-Control: no-store\n"
        )
    for route in ("/checkout", "/checkout/*", "/encomenda/*", "/orcamento/*", "/avaliar/*"):
        result += f"\n{route}\n  Cache-Control: no-store\n  X-Robots-Tag: noindex\n"
    result += "\n/assets/*\n  Cache-Control: public, max-age=0, must-revalidate\n"
    return result
